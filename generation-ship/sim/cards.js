// Card balance report: pick rate (played / drawn), heir rate, and win rate in games where the card
// was played, across many bot games. Writes sim/CARDS.md and data/card_stats.json.
//   node sim/cards.js --games 60
import { Worker, isMainThread, parentPort, workerData } from "node:worker_threads";
import { fileURLToPath } from "node:url";
import { writeFileSync, readFileSync } from "node:fs";

if (!isMainThread) {
  const { loadData } = await import("./load.js");
  const { playGame } = await import("../src/engine/game.js");
  const { Bot } = await import("../src/ai/bots.js");
  const data = loadData();
  const { houses, games, seed } = workerData;
  const cards = {}; let wins = 0;
  for (let g = 0; g < games; g++) {
    const st = playGame(data, houses.map((_, i) => new Bot(3, seed * 1000 + g * 10 + i)), { players: 2, houses, trackCards: true }, seed * 7919 + g);
    const win = st.result.outcome === "win";
    if (win) wins++;
    for (const [id, c] of Object.entries(st.stats.cards || {})) {
      const a = (cards[id] ??= { drawn: 0, played: 0, nominated: 0, leader: 0, gamesPlayed: 0, winsPlayed: 0 });
      a.drawn += c.drawn; a.played += c.played; a.nominated += c.nominated; a.leader += c.leader;
      if (c.played) { a.gamesPlayed++; if (win) a.winsPlayed++; }
    }
  }
  parentPort.postMessage({ cards, games, wins });
} else {
  const argv = process.argv.slice(2);
  const games = Number(argv[argv.indexOf("--games") + 1] || 60);
  const H = JSON.parse(readFileSync(new URL("../data/houses.json", import.meta.url))).houses.map((h) => h.id);
  const pairs = [];
  for (let i = 0; i < H.length; i++) for (let j = i + 1; j < H.length; j++) pairs.push([H[i], H[j]]);
  const run = (job) => new Promise((res, rej) => { const w = new Worker(fileURLToPath(import.meta.url), { workerData: job }); w.on("message", res); w.on("error", rej); });
  const total = {}; let G = 0, W = 0;
  for (let k = 0; k < pairs.length; k += 4) {
    for (const r of await Promise.all(pairs.slice(k, k + 4).map((houses, i) => run({ houses, games, seed: 500 + k + i })))) {
      G += r.games; W += r.wins;
      for (const [id, c] of Object.entries(r.cards)) { const a = (total[id] ??= {}); for (const [k2, v] of Object.entries(c)) a[k2] = (a[k2] || 0) + v; }
    }
  }
  const people = JSON.parse(readFileSync(new URL("../data/people.json", import.meta.url)));
  const base = W / G;
  const rows = people.map((c) => {
    const s = total[c.id] || { drawn: 0, played: 0, nominated: 0, leader: 0, gamesPlayed: 0, winsPlayed: 0 };
    return { id: c.id, tier: c.tier, cost: c.cost, text: c.text, drawn: s.drawn, pick: s.drawn ? s.played / s.drawn : 0,
      heir: s.nominated ? s.leader / s.nominated : 0, winWhenPlayed: s.gamesPlayed ? s.winsPlayed / s.gamesPlayed : null, gamesPlayed: s.gamesPlayed };
  });
  writeFileSync(new URL("../data/card_stats.json", import.meta.url), JSON.stringify({ games: G, baseWin: base, rows }, null, 0));
  const byTier = (t) => rows.filter((r) => r.tier === t && r.drawn >= 20);
  const pct = (x) => (x === null ? "-" : `${(100 * x).toFixed(0)}%`);
  let md = `# Card balance report\n\nHouse bots, all 28 two-house pairings, ${G} games (base win rate ${pct(base)}). Generated by \`sim/cards.js\`.\n\n`;
  md += "- **Pick rate** = how often a card is played when it's in hand. Bots play what they value, so this is the clearest signal.\n- **Heir rate** = how often the card wins the vote when nominated.\n- **Win when played** is confounded with game state; use it only alongside pick rate.\n\n";
  for (const t of ["Common", "Remarkable"]) {
    const rs = byTier(t);
    const avgPick = rs.reduce((n, r) => n + r.pick, 0) / rs.length;
    const sd = Math.sqrt(rs.reduce((n, r) => n + (r.pick - avgPick) ** 2, 0) / rs.length);
    md += `## ${t} (${rs.length} cards with 20+ draws; average pick rate ${pct(avgPick)}, spread ±${pct(sd)})\n\n`;
    for (const cost of [...new Set(rs.map((r) => r.cost))].sort((a, b) => a - b)) {
      const c = rs.filter((r) => r.cost === cost);
      md += `- Cost ${cost}: ${c.length} cards, average pick rate ${pct(c.reduce((n, r) => n + r.pick, 0) / c.length)}\n`;
    }
    const tbl = (list) => "| Card | Cost | Effect | Pick | Heir | Win when played |\n|---|---|---|---|---|---|\n" +
      list.map((r) => `| ${r.id} | ${r.cost} | ${r.text} | ${pct(r.pick)} | ${pct(r.heir)} | ${pct(r.winWhenPlayed)} |`).join("\n") + "\n\n";
    const sorted = [...rs].sort((a, b) => b.pick - a.pick);
    md += `\n### Most picked (possibly underpriced)\n\n${tbl(sorted.slice(0, 12))}### Least picked (possibly overpriced or weak)\n\n${tbl(sorted.slice(-12).reverse())}`;
  }
  writeFileSync(new URL("./CARDS.md", import.meta.url), md);
  console.log(md.split("\n").slice(0, 30).join("\n"));
}
